"""Deterministic synthetic benchmark prompts (goal.md §14, §44).

Prompts are generated by a seeded RNG so a given (cell, repetition) always
produces the same token sequence — reproducible without persisting prompt
contents (synthetic data by default).
"""

from __future__ import annotations

import hashlib
import random
from dataclasses import dataclass


# A vocabulary of common English words; sampling from it gives realistic
# tokenization density (~1 token per ~4-5 chars) for most BPE tokenizers.
_WORD_BANK: list[str] = (
    "the quick brown fox jumps over a lazy dog near the old river bank "
    "while the wind carries soft clouds across the open sky and the "
    "gentle morning light reflects off the calm water surface below the "
    "quiet village where people walk their dogs along the stone path "
    "toward the small market square in the center of the town each day "
    "through the seasons of spring summer autumn and winter in the "
    "surrounding countryside of rolling green hills and deep forested "
    "valleys that stretch toward the distant mountain range on the "
    "western horizon beneath the changing evening stars of the clear "
    "night sky above the peaceful valley floor and the winding river "
    "that flows through the fertile fields and past the ancient oak "
    "trees that have stood for many hundreds of years in the cool "
    "valley breeze of the early morning hours before the sun rises "
    "over the eastern ridge of the highland plateau to the north of "
    "the river delta where the wetland marshes provide habitat for "
    "wildlife and migratory birds that pass through the region during "
    "the long journey between their summer and winter homes each year "
).split()


@dataclass
class PromptSpec:
    """A generated prompt with its measured properties."""

    text: str
    approx_tokens: int  # rough estimate (not authoritative)
    seed_hash: str


def _make_rng(cell_seed: int, repetition: int, variant: int) -> random.Random:
    seed = (cell_seed * 7919 + repetition * 104729 + variant) % (2**31 - 1)
    return random.Random(seed)


def generate_prompt(
    target_tokens: int,
    cell_seed: int = 0,
    repetition: int = 0,
    variant: int = 0,
    tokenizer: str | None = None,
) -> PromptSpec:
    """Generate a synthetic prompt of approximately ``target_tokens``.

    ``variant`` controls the prompt's identity — used for cold-cache workloads
    (each variant is a unique prompt) and warm-cache workloads (the same
    variant is repeated to build a reusable KV prefix).
    """
    if target_tokens <= 0:
        return PromptSpec("", 0, hashlib.sha256(b"").hexdigest())
    rng = _make_rng(cell_seed, repetition, variant)
    # ~2 words per token keeps a generous margin (English text tokenizes at
    # roughly 0.75-1 word/token); the slight overshoot is fine for benches.
    words_needed = int(target_tokens * 2.0) + 8
    words = [rng.choice(_WORD_BANK) for _ in range(words_needed)]
    # A deterministic leading prefix for warm-cache reuse (shared across
    # repetitions when variant is fixed).
    prefix = rng.choice(_WORD_BANK)
    text = (" ".join(words))
    if tokenizer is None:
        # rough: assume ~4.5 chars/token
        approx = max(1, len(text) // 5)
    else:
        approx = target_tokens
    digest = hashlib.sha256(f"{cell_seed}:{repetition}:{variant}:{len(text)}".encode()).hexdigest()
    return PromptSpec(text=text, approx_tokens=approx, seed_hash=digest[:16])


def warm_prefix_prompt(
    target_tokens: int,
    prefix_tokens: int,
    variant: int,
) -> PromptSpec:
    """A prompt that starts with a shared prefix (for warm-cache testing).

    The first ``prefix_tokens`` are drawn from a *shared* seed so all
    variants of the same warm workload reuse the same prefix (building a
    warm KV cache), while the tail is unique per variant.
    """
    shared_rng = random.Random("warm-shared-prefix")
    prefix_words = [shared_rng.choice(_WORD_BANK)
                    for _ in range(max(1, prefix_tokens))]
    tail = generate_prompt(target_tokens - prefix_tokens, variant=variant,
                           repetition=0, cell_seed=0)
    text = " ".join(prefix_words) + " " + tail.text
    approx = max(1, len(text) // 5)
    digest = hashlib.sha256(f"warm:{variant}:{len(text)}".encode()).hexdigest()
    return PromptSpec(text=text, approx_tokens=approx, seed_hash=digest[:16])
